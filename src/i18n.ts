export type TranslationKey = keyof typeof dict.zh;

export function translate(language: Language, key: TranslationKey, params?: Record<string, string | number>) {
  let value: string = dict[language][key] ?? dict.zh[key];
  if (params) {
    Object.entries(params).forEach(([name, replacement]) => {
      value = value.split(`{${name}}`).join(String(replacement));
    });
  }
  return value;
}

export function useTranslation() {
  const language = useUiStore((state) => state.language);
  return {
    language,
    t: (key: TranslationKey, params?: Record<string, string | number>) => translate(language, key, params),
  };
}
